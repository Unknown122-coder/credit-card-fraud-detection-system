@st.cache_resource
def get_local_artifacts() -> Optional[Any]:
    """Load local model artifacts for in-process fallback (e.g. Streamlit Cloud)."""
    try:
        from src.artifacts.save import load_model_artifacts
        from src.config import get_settings

        # Check configured directory
        try:
            settings = get_settings()
            if (settings.model_dir / "champion_pipeline.joblib").exists():
                return load_model_artifacts(settings.model_dir, verify_checksums=False)
        except Exception as config_err:
            logger.warning(f"Settings path check fallback: {config_err}")

        # Check repository fallback directory
        direct_dir = REPO_ROOT / "models" / "registry"
        if (direct_dir / "champion_pipeline.joblib").exists():
            return load_model_artifacts(direct_dir, verify_checksums=False)
    except Exception as exc:
        logger.error(f"In-process artifact load failure: {exc}")
    return None


@st.cache_data(ttl=10)
def check_api_health() -> Optional[dict[str, Any]]:
    """Query FastAPI liveness probe, falling back to local in-process model if running standalone."""
    try:
        resp = requests.get(f"{API_BASE_URL}/health", timeout=1.5)
        if resp.status_code == 200:
            return resp.json()
    except Exception:
        pass

    local = get_local_artifacts()
    if local is not None:
        version = "1.0.0"
        if hasattr(local, "metadata") and isinstance(local.metadata, dict):
            version = local.metadata.get("version", "1.0.0")
        return {
            "status": "healthy",
            "model_version": f"{version} (Cloud Standalone)",
            "operating_threshold": getattr(local, "threshold", 0.048),
        }
    return None


