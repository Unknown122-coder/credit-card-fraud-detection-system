def sanitize_csv_injection(df_to_clean: pd.DataFrame) -> pd.DataFrame:
    """Prefix text fields starting with formula characters with a single quote to neutralize CSV injection."""
    cleaned = df_to_clean.copy()
    triggers = ("=", "+", "-", "@", "\t", "\r")
    for col in cleaned.select_dtypes(include=["object"]).columns:
        cleaned[col] = (
            cleaned[col]
            .astype(str)
            .apply(lambda val: f"'{val}" if val.startswith(triggers) else val)
        )
    return cleaned


@st.cache_resource
def _rebuild_explainer(_local: Any) -> Optional[Any]:
    """Build a fresh explainer when the serialized one cannot run in this environment.

    Reuses the background sample carried by the serialized explainer so the
    rebuilt backend keeps the original attribution reference point. Streamlit's
    cache keeps this to once per session.
    """
    try:
        from src.explain.shap_utils import build_explainer_for_model, extract_background

        explainer = build_explainer_for_model(
            _local.pipeline, background=extract_background(_local.explainer)
        )
        if explainer is not None:
            logger.info(
                "Rebuilt %s in-process for runtime compatibility",
                type(explainer).__name__,
            )
        return explainer
    except Exception as exc:
        logger.error(f"Failed to rebuild SHAP explainer: {exc}")
        return None


def call_predict(payload: dict[str, Any]) -> Optional[dict[str, Any]]:
    """Send scoring request to /predict endpoint, with seamless in-process fallback."""
    try:
        resp = requests.post(f"{API_BASE_URL}/predict", json=payload, timeout=5.0)
        if resp.status_code == 200:
            return resp.json()
    except Exception:
        pass

    # In-process fallback for cloud hosting (e.g. Streamlit Community Cloud)
    local = get_local_artifacts()
    if local is not None:
        try:
            from app.api.main import score_dataframe

            df = pd.DataFrame([payload["transaction"]])[FEATURE_COLS]
            thresh = payload.get("override_threshold")
            if thresh is None:
                thresh = local.threshold
            probs, decisions, costs = score_dataframe(
                df, local, threshold=float(thresh)
            )
            return {
                "fraud_probability": float(probs[0]),
                "decision": int(decisions[0]),
                "operating_threshold": float(thresh),
                "model_version": local.metadata.get("version", "1.0.0"),
                "expected_cost": round(float(costs[0]), 2),
            }
        except Exception as exc:
            st.error(f"In-process prediction error: {exc}")
            return None

    st.error(
        f"Cannot reach prediction service at {API_BASE_URL} and no local model found."
    )
    return None


def call_explain(payload: dict[str, Any]) -> Optional[dict[str, Any]]:
    """Send explanation request to /explain endpoint, with seamless in-process fallback."""
    try:
        resp = requests.post(f"{API_BASE_URL}/explain", json=payload, timeout=8.0)
        if resp.status_code == 200:
            return resp.json()
    except Exception:
        pass

    local = get_local_artifacts()
    if local is not None:
        try:
            from src.explain.shap_utils import compute_local_explanation

            df = pd.DataFrame([payload["transaction"]])[FEATURE_COLS]

            # Prefer the serialized explainer, but fall back to one rebuilt
            # in-process when the installed shap/booster versions cannot read it
            explanation = None
            if local.explainer is not None:
                try:
                    explanation = compute_local_explanation(
                        local.explainer, df, top_n=10, pipeline=local.pipeline
                    )
                except Exception as exc:
                    logger.warning(
                        f"Serialized SHAP explainer unusable in this environment: {exc}"
                    )

            if explanation is None:
                explainer = _rebuild_explainer(local)
                if explainer is None:
                    st.warning(
                        "SHAP attribution is unavailable in this environment. "
                        "Generate the explainer locally with: `make explain`"
                    )
                    return None
                explanation = compute_local_explanation(
                    explainer, df, top_n=10, pipeline=local.pipeline
                )

            return {
                "base_value": explanation["base_value"],
                "prediction_score": explanation["prediction_score"],
                "top_attributions": explanation["top_attributions"],
                "summary_text": explanation["summary_text"],
            }
        except Exception as exc:
            logger.error(f"In-process SHAP error: {exc}")
            st.warning(f"In-process SHAP calculation notice: {exc}")
            return None

    st.warning("Local explanation could not be generated for this transaction.")
    return None


def call_predict_batch_csv(
    file_bytes: bytes, threshold: float
) -> Optional[dict[str, Any]]:
    """Upload CSV to /predict_batch_csv, with seamless in-process fallback."""
    try:
        files = {"file": ("upload.csv", file_bytes, "text/csv")}
        params = {"override_threshold": threshold}
        resp = requests.post(
            f"{API_BASE_URL}/predict_batch_csv",
            files=files,
            params=params,
            timeout=60.0,
        )
        if resp.status_code == 200:
            return resp.json()
    except Exception:
        pass

    local = get_local_artifacts()
    if local is not None:
        try:
            from app.api.main import score_dataframe

            df = pd.read_csv(io.BytesIO(file_bytes))
            for col in FEATURE_COLS:
                df[col] = pd.to_numeric(df[col], errors="coerce").fillna(0.0)
            probs, decisions, costs = score_dataframe(
                df[FEATURE_COLS], local, threshold=threshold
            )
            results = []
            for p, d, c in zip(probs, decisions, costs):
                results.append(
                    {
                        "fraud_probability": float(p),
                        "decision": int(d),
                        "operating_threshold": float(threshold),
                        "model_version": local.metadata.get("version", "1.0.0"),
                        "expected_cost": round(float(c), 2),
                    }
                )
            total = len(results)
            flagged = int(sum(decisions))
            return {
                "total_processed": total,
                "flagged_count": flagged,
                "flagged_ratio": round(flagged / max(total, 1), 4),
                "operating_threshold": float(threshold),
                "model_version": local.metadata.get("version", "1.0.0"),
                "results": results,
            }
        except Exception as exc:
            st.error(f"In-process batch scoring failed: {exc}")
            return None

    st.error(f"Batch API connection failed at {API_BASE_URL}.")
    return None


